CREATE TABLE BILLING_ACCOUNTS (
  ACCOUNT_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ACCOUNT_NUMBER VARCHAR(40) NOT NULL,
  ACCOUNT_NAME VARCHAR(160) NOT NULL,
  BILLING_CONTACT VARCHAR(160) NOT NULL,
  BILLING_EMAIL VARCHAR(254) NOT NULL,
  BILLING_PHONE VARCHAR(40) NOT NULL,
  BILLING_ADDRESS VARCHAR(500) NOT NULL,
  PAYMENT_TERMS VARCHAR(80) NOT NULL,
  STATUS VARCHAR(20) NOT NULL DEFAULT 'Active',
  PRIMARY KEY (ACCOUNT_ID),
  CONSTRAINT BILLING_ACCOUNTS_NUMBER_UQ UNIQUE (ACCOUNT_NUMBER),
  CONSTRAINT BILLING_ACCOUNTS_STATUS_CK
    CHECK (STATUS IN ('Active', 'Pending', 'On hold', 'Closed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;